"""Generate transport types from the single current-map JSON schema."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
schema = json.loads((ROOT / "schemas/map-observation-v1.json").read_text())


def ts(node):
    if "const" in node:
        return f"Type.Literal({json.dumps(node['const'])})"
    if "enum" in node:
        return f"Type.Enum({json.dumps(node['enum'])} as const)"
    kind = node["type"]
    if kind == "object":
        fields = []
        for key, value in node["properties"].items():
            expression = ts(value)
            if key not in node.get("required", []):
                expression = f"Type.Optional({expression})"
            fields.append(f"{key}: {expression}")
        return "Type.Object({" + ",".join(fields) + "},{additionalProperties:false})"
    if "prefixItems" in node:
        return "Type.Tuple([" + ",".join(ts(v) for v in node["prefixItems"]) + "])"
    options = {k: v for k, v in node.items() if k not in ("type", "items", "$schema", "$id")}
    if kind == "array":
        return f"Type.Array({ts(node['items'])},{json.dumps(options)})"
    return f"Type.{kind.title()}({json.dumps(options)})"


def py_type(node):
    if "prefixItems" in node:
        return "tuple[" + ", ".join(py_type(v) for v in node["prefixItems"]) + "]"
    return {"integer": "int", "string": "str"}[node["type"]]


element = schema["properties"]["elements"]["items"]
lines = [
    '"""Generated by scripts/map-observation-schema.py; edit schemas/map-observation-v1.json."""',
    "", "from dataclasses import dataclass", "", "", "@dataclass(frozen=True)",
    "class MapElement:",
]
for key, value in element["properties"].items():
    annotation = py_type(value)
    if key not in element["required"]:
        annotation += " | None = None"
    lines.append(f"    {key}: {annotation}")
outputs = {ROOT / "env/pokebench_env/map_observation_types.py": "\n".join(lines) + "\n"}
outputs[ROOT / "packages/agent/src/map-observation.generated.ts"] = (
    '// Generated by scripts/map-observation-schema.py; edit schemas/map-observation-v1.json.\n'
    'import {Type,type Static} from "typebox";\n'
    f"export const MapObservationSchema = {ts(schema)};\n"
    'export type MapObservation = Static<typeof MapObservationSchema>;\n'
)

for path, content in outputs.items():
    if "--check" in sys.argv:
        if path.read_text() != content:
            raise SystemExit(f"generated map contract differs: {path}")
    else:
        path.write_text(content)
