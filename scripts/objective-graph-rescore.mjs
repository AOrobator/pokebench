// Offline re-score only: reads immutable run event streams, never calls a model or emulator.
// Scores every recorded run twice — once by the linear record order, once by graph depth — and
// reports where the two disagree about how far a run got.
import {createReadStream} from "node:fs";
import {readdir,writeFile} from "node:fs/promises";
import {createInterface} from "node:readline";
import {join,resolve} from "node:path";
import {checkEvent} from "../packages/agent/dist/events.js";
import {REQUIRED_FRONTIER_MILESTONES} from "../packages/agent/dist/milestones.js";
import {OBJECTIVE_NODES,objectiveDepth,remainingToClear,enabledObjectives} from "../packages/agent/dist/objective-graph.js";

const repo=resolve(new URL("..",import.meta.url).pathname);
const runs=process.argv[2]??join(repo,"runs");
const out=process.argv[3]??join(repo,"docs/findings/objective-graph-rescore.md");
const order=[...REQUIRED_FRONTIER_MILESTONES];
const indexOf=new Map(order.map((name,index)=>[name,index]));
const BADGES=["STONE_BADGE","DYNAMO_BADGE","HEAT_BADGE","KNUCKLE_BADGE","BALANCE_BADGE","FEATHER_BADGE","MIND_BADGE","RAIN_BADGE"];
// A drought shorter than this is ordinary play; the record run's worst was 658 turns.
const DROUGHT=200;

const marksIn=async(file)=>{
  const marks=[];
  const lines=createInterface({input:createReadStream(file),crlfDelay:Infinity});
  for await(const line of lines){
    if(!line.includes('"type":"milestone"'))continue;
    const event=checkEvent(JSON.parse(line));
    if(event.type!=="milestone")continue;
    marks.push({turn:event.turn,name:event.name,kind:event.kind??""});
  }
  return marks;
};

const frontierAt=(reached)=>{
  let furthest=-1;
  for(const name of reached)furthest=Math.max(furthest,indexOf.get(name)??-1);
  return furthest;
};

const rows=[];
const skipped=[];
for(const entry of await readdir(runs,{withFileTypes:true})){
  if(!entry.isDirectory())continue;
  let marks;
  try{marks=await marksIn(join(runs,entry.name,"events.jsonl"));}
  catch(error){
    if(!(error instanceof Error&&"code" in error&&error.code==="ENOENT"))skipped.push({run:entry.name,reason:error instanceof Error?error.message.slice(0,120):String(error)});
    continue;
  }
  if(marks.length===0)continue;
  const reached=new Set(marks.map(mark=>mark.name));
  const droughts=[];
  const walked=new Set();
  let storySeen=null;
  for(const mark of marks){
    if(mark.kind==="story"&&storySeen!==null&&mark.turn-storySeen.turn>=DROUGHT){
      const atStart=new Set(walked);
      const furthest=frontierAt(atStart);
      const linearNext=furthest+1<order.length?order[furthest+1]:"";
      droughts.push({gap:mark.turn-storySeen.turn,from:storySeen.name,to:mark.name,linearNext,
        offLinear:linearNext!==mark.name,enabled:enabledObjectives(atStart).filter(id=>!atStart.has(id)).length});
    }
    walked.add(mark.name);
    if(mark.kind==="story")storySeen=mark;
  }
  rows.push({run:entry.name,badges:BADGES.filter(name=>reached.has(name)).length,depth:objectiveDepth(reached),
    frontier:frontierAt(reached)+1,remaining:remainingToClear(reached),droughts});
}

const droughts=rows.flatMap(row=>row.droughts);
const eligible=rows.filter(row=>row.badges>=2).sort((a,b)=>b.depth-a.depth);
const divergence=rows.filter(row=>row.frontier>0).map(row=>row.frontier-row.depth);
const mean=list=>list.reduce((sum,value)=>sum+value,0)/list.length;
const pct=(part,whole)=>whole===0?"—":`${String(Math.round((part/whole)*100))}%`;
const table=(header,cells)=>[`| ${header.join(" | ")} |`,`| ${header.map(()=>"---").join(" | ")} |`,...cells.map(cell=>`| ${cell.join(" | ")} |`)].join("\n");

const report=[
"# Objective graph, measured against every recorded run",
"",
"Generated by `scripts/objective-graph-rescore.mjs`; re-run it rather than editing this file.",
"",
"## Method",
"",
`Every run directory under \`runs/\` whose \`events.jsonl\` holds at least one \`milestone\` event — ${String(rows.length)} runs.`,
"For each run the reached set is the names of its milestone events, and two numbers are computed from it:",
"",
"- **Record order**: the furthest index reached in `REQUIRED_FRONTIER_MILESTONES`, which is what the viewer's",
"  `furthestMilestone` reports today.",
"- **Depth**: `objectiveDepth(R)` — reached, non-optional objectives whose hard prerequisites are also",
"  reached. Independent of the order they arrived in.",
"",
"A **drought** is a gap of 200+ turns between two consecutive `kind: \"story\"` milestones. For each one the",
"re-score records what the linear frontier named as next at the moment the drought began, and whether the",
"run's actual next story milestone was something else.",
"",
...(skipped.length===0?[]:["",
  `${String(skipped.length)} run(s) hold an \`events.jsonl\` that could not be read as a valid event stream, and are excluded:`,
  ...skipped.map(entry=>`- \`${entry.run}\` — ${entry.reason}`)]),
"",
"## The pool",
"",
table(["badges","runs"],[0,1,2,3,4,5,6,7,8].map(count=>[String(count),String(rows.filter(row=>row.badges===count).length)])),
"",
`${String(eligible.length)} runs reached two or more badges. Nothing in the pool has reached the fifth badge,`,
"so every statement below about deferral is supported by early-game runs only. That is a limit of the",
"evidence, not of the graph.",
"",
"## Depth against record order",
"",
`Across all ${String(rows.length)} runs the record-order index is never below depth and runs an average of`,
`${mean(divergence).toFixed(1)} positions higher (max ${String(Math.max(...divergence))}). It credits a run for a`,
"milestone whose prerequisites are still missing, which depth refuses to do.",
"",
`Runs that reached two or more badges, ranked by depth (of ${String(OBJECTIVE_NODES.length)} recordable objectives):`,
"",
table(["run","badges","depth","record order","long droughts","off-linear"],
  eligible.map(row=>[`\`${row.run}\``,String(row.badges),String(row.depth),String(row.frontier),
    String(row.droughts.length),String(row.droughts.filter(d=>d.offLinear).length)])),
"",
`Depth and record order are not two rescalings of one number: the index reports the furthest position reached`,
"in a list, depth reports how many objectives were closed. They agree in rank when a run followed the record",
"order and part company when it did not — `qwen36-gpu1_d41e` closes 87 objectives while the list credits it 140",
"and `glm53-mac_6bbd` closes 82 while the list credits it 140.",
"",
"## Distance to a clear",
"",
`\`remainingToClear\` reads 14 for every run in the pool, and that is not a bug: a cleared game's hard-gated`,
"closure is the league sequence behind badge six, and no run here has reached badge six. The number is a",
"late-game distance, constant and uninformative before then — so it is reported in the run cards, not as",
"progress. Depth is the usable half.",
"",
"## Droughts",
"",
`${String(droughts.length)} droughts of 200+ turns across the pool.`,
`- ${String(droughts.filter(d=>d.offLinear).length)} (${pct(droughts.filter(d=>d.offLinear).length,droughts.length)}) ended on a story milestone that was **not** the one the linear frontier named next.`,
`- ${String(droughts.filter(d=>d.enabled>0).length)} (${pct(droughts.filter(d=>d.enabled>0).length,droughts.length)}) began with at least one objective enabled by the graph.`,
"",
"Longest droughts in the pool:",
"",
table(["turns","run","from","to","frontier named next"],droughts.slice().sort((a,b)=>b.gap-a.gap).slice(0,10).map(d=>
  [String(d.gap),`\`${rows.find(row=>row.droughts.includes(d))?.run??""}\``,`\`${d.from}\``,`\`${d.to}\``,d.linearNext===""?"—":`\`${d.linearNext}\``])),
"",
"## What this supports, and what it does not",
"",
"- **Supported:** a run can be scored on closure rather than list position, retroactively, from events already",
"  on disk. Depth is monotone and order-independent, so a deferred badge scores the same as an early one.",
"- **Supported:** in most long droughts the linear frontier was naming a milestone the run was not going to",
"  reach next. That is the shape of the Rustboro-from-Mauville nag.",
"- **Not supported:** that the supervisor's nags would have been suppressed. The recorded `loop_guard`",
"  `milestone_drought` payload carries a stall briefing with no milestone id, so *which* objective the",
"  supervisor was pressing for is unrecoverable from these runs. Counting corrections suppressed needs the",
"  briefing to name its target first.",
].join("\n")+"\n";

await writeFile(out,report);
console.log(`wrote ${out}: ${String(rows.length)} runs, ${String(droughts.length)} droughts, ` +
  `${String(droughts.filter(d=>d.offLinear).length)} off-linear, mean frontier-depth ${mean(divergence).toFixed(1)}`);
